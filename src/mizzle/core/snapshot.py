"""Snapshot: a JSON-serializable picture of a database schema.

Built from Python tables (``kit.snapshot``) or read from a live database (dialect
introspection). Migrations are generated by diffing two snapshots. All SQL fragments
(types, defaults, expressions) are stored in the dialect's normalized form so that a
schema and the database it created compare equal.
"""

from __future__ import annotations

import re
from typing import Literal, NotRequired, TypedDict

SNAPSHOT_VERSION = 1


class IdentitySnap(TypedDict):
    always: bool  # GENERATED ALWAYS (else BY DEFAULT)
    start: int
    increment: int
    # Absent when the database default (see ``sequence_defaults``), so older snapshots
    # compare equal.
    min_value: NotRequired[int]
    max_value: NotRequired[int]
    cache: NotRequired[int]  # default 1
    cycle: NotRequired[bool]  # default false


_INT_MAX = {"smallint": 2**15 - 1, "integer": 2**31 - 1, "bigint": 2**63 - 1}


def sequence_defaults(sql_type: str, increment: int) -> tuple[int, int]:
    """MINVALUE and MAXVALUE a sequence of ``sql_type`` gets when they are not given."""
    top = _INT_MAX.get(sql_type, _INT_MAX["bigint"])
    return (1, top) if increment > 0 else (-top - 1, -1)


class GeneratedSnap(TypedDict):
    expression: str
    stored: bool  # STORED (else VIRTUAL)


class ColumnSnap(TypedDict):
    name: str
    type: str  # normalized SQL type, or "serial" / "bigserial" / "smallserial"
    not_null: bool
    default: str | None  # normalized SQL expression
    # Absent unless set, so snapshots written before these fields existed compare equal.
    identity: NotRequired[IdentitySnap]
    generated: NotRequired[GeneratedSnap]
    collation: NotRequired[str]  # COLLATE name, when not the database default
    comment: NotRequired[str]  # COMMENT ON COLUMN


class PrimaryKeySnap(TypedDict):
    name: str
    columns: list[str]
    deferrable: NotRequired[bool]
    initially_deferred: NotRequired[bool]


class UniqueSnap(TypedDict):
    name: str
    columns: list[str]
    # Absent when the default (NULLs are distinct), so older snapshots compare equal.
    nulls_not_distinct: NotRequired[bool]
    deferrable: NotRequired[bool]
    initially_deferred: NotRequired[bool]


class CheckSnap(TypedDict):
    name: str
    expression: str
    not_valid: NotRequired[bool]


class ForeignKeySnap(TypedDict):
    name: str
    columns: list[str]
    ref_schema: str
    ref_table: str
    ref_columns: list[str]
    on_delete: str | None  # None means the database default (NO ACTION)
    on_update: str | None
    deferrable: NotRequired[bool]
    initially_deferred: NotRequired[bool]
    not_valid: NotRequired[bool]


class IndexSnap(TypedDict):
    name: str
    columns: list[str]  # plain column keys; empty when ``expression`` is set
    unique: bool
    where: str | None
    # Key list as SQL, for indexes on expressions (e.g. "lower(email)"). Absent otherwise,
    # so snapshots written before this field existed compare equal.
    expression: NotRequired[str]
    method: NotRequired[str]  # access method; absent means btree
    # Non-default operator class per column (None: the default); plain-column indexes only.
    # Expression indexes carry theirs inside ``expression``.
    opclasses: NotRequired[list[str | None]]
    options: NotRequired[dict[str, str]]  # storage parameters: WITH (m = 16, ...)
    nulls_not_distinct: NotRequired[bool]  # UNIQUE index: NULLs are equal


class RlsSnap(TypedDict):
    enabled: bool
    force: bool


class PolicySnap(TypedDict):
    name: str
    command: str  # "all", "select", "insert", "update" or "delete"
    permissive: bool  # else restrictive
    roles: list[str]  # sorted; "public" is everyone
    using: str | None  # normalized SQL expressions
    with_check: str | None


class TableSnap(TypedDict):
    schema: str
    name: str
    columns: dict[str, ColumnSnap]  # db column name -> column, in table order
    primary_key: PrimaryKeySnap | None
    uniques: dict[str, UniqueSnap]
    checks: dict[str, CheckSnap]
    foreign_keys: dict[str, ForeignKeySnap]
    indexes: dict[str, IndexSnap]
    # Absent unless used, so snapshots written before these fields existed compare equal.
    rls: NotRequired[RlsSnap]
    policies: NotRequired[dict[str, PolicySnap]]
    comment: NotRequired[str]  # COMMENT ON TABLE
    unlogged: NotRequired[bool]  # CREATE UNLOGGED TABLE
    options: NotRequired[dict[str, str]]  # storage parameters: WITH (fillfactor=70)


class EnumSnap(TypedDict):
    schema: str
    name: str
    values: list[str]


class RoleSnap(TypedDict):
    name: str
    login: bool
    create_db: bool
    create_role: bool
    inherit: bool


class ViewSnap(TypedDict):
    schema: str
    name: str
    definition: str  # the query; normalized by the database when compared with one
    materialized: bool
    # The declared columns: only for `pull`; the diff ignores them.
    columns: dict[str, ColumnSnap]
    indexes: NotRequired[dict[str, IndexSnap]]  # materialized views only
    # View options (K6); absent when off, so older snapshots compare equal.
    security_invoker: NotRequired[bool]
    security_barrier: NotRequired[bool]
    check_option: NotRequired[Literal["local", "cascaded"]]


class Snapshot(TypedDict):
    version: int
    dialect: str
    id: str
    prev_id: str | None
    schemas: list[str]  # schemas other than the dialect default that objects live in
    enums: dict[str, EnumSnap]  # "schema.name" -> enum
    tables: dict[str, TableSnap]  # "schema.name" -> table
    # Absent unless used, so snapshots written before these fields existed compare equal.
    roles: NotRequired[dict[str, RoleSnap]]  # name -> role (managed ones only)
    views: NotRequired[dict[str, ViewSnap]]  # "schema.name" -> view


def key(schema: str, name: str) -> str:
    return f"{schema}.{name}"


# Defaults that are SQL keywords, not functions (current_user, current_timestamp(3)...).
_KEYWORD_DEFAULT = re.compile(
    r"(?:current_(?:user|role|timestamp|date|time|catalog|schema)|session_user|user"
    r"|localtimestamp|localtime)(?:\s*\(\s*\d+\s*\))?",
    re.IGNORECASE,
)


def keyword_default(text: str) -> str:
    """A default that is an SQL keyword in upper case (``CURRENT_USER``), as databases
    print it back; anything else unchanged. Snapshots written before this stored them as
    declared, so the diff compares through it too."""
    return text.upper().replace(" ", "") if _KEYWORD_DEFAULT.fullmatch(text) else text


def empty_snapshot(dialect: str, id: str = "00000000-0000-0000-0000-000000000000") -> Snapshot:
    return Snapshot(
        version=SNAPSHOT_VERSION,
        dialect=dialect,
        id=id,
        prev_id=None,
        schemas=[],
        enums={},
        tables={},
    )
