"""Snapshot: a JSON-serializable picture of a database schema.

Built from Python tables (``kit.snapshot``) or read from a live database (dialect
introspection). Migrations are generated by diffing two snapshots. All SQL fragments
(types, defaults, expressions) are stored in the dialect's normalized form so that a
schema and the database it created compare equal.
"""

from __future__ import annotations

from typing import NotRequired, TypedDict

SNAPSHOT_VERSION = 1


class ColumnSnap(TypedDict):
    name: str
    type: str  # normalized SQL type, or "serial" / "bigserial" / "smallserial"
    not_null: bool
    default: str | None  # normalized SQL expression


class PrimaryKeySnap(TypedDict):
    name: str
    columns: list[str]


class UniqueSnap(TypedDict):
    name: str
    columns: list[str]


class CheckSnap(TypedDict):
    name: str
    expression: str


class ForeignKeySnap(TypedDict):
    name: str
    columns: list[str]
    ref_schema: str
    ref_table: str
    ref_columns: list[str]
    on_delete: str | None  # None means the database default (NO ACTION)
    on_update: str | None


class IndexSnap(TypedDict):
    name: str
    columns: list[str]  # plain column keys; empty when ``expression`` is set
    unique: bool
    where: str | None
    # Key list as SQL, for indexes on expressions (e.g. "lower(email)"). Absent otherwise,
    # so snapshots written before this field existed compare equal.
    expression: NotRequired[str]


class TableSnap(TypedDict):
    schema: str
    name: str
    columns: dict[str, ColumnSnap]  # db column name -> column, in table order
    primary_key: PrimaryKeySnap | None
    uniques: dict[str, UniqueSnap]
    checks: dict[str, CheckSnap]
    foreign_keys: dict[str, ForeignKeySnap]
    indexes: dict[str, IndexSnap]


class EnumSnap(TypedDict):
    schema: str
    name: str
    values: list[str]


class Snapshot(TypedDict):
    version: int
    dialect: str
    id: str
    prev_id: str | None
    schemas: list[str]  # schemas other than the dialect default that tables live in
    enums: dict[str, EnumSnap]  # "schema.name" -> enum
    tables: dict[str, TableSnap]  # "schema.name" -> table


def key(schema: str, name: str) -> str:
    return f"{schema}.{name}"


def empty_snapshot(dialect: str, id: str = "00000000-0000-0000-0000-000000000000") -> Snapshot:
    return Snapshot(
        version=SNAPSHOT_VERSION,
        dialect=dialect,
        id=id,
        prev_id=None,
        schemas=[],
        enums={},
        tables={},
    )
