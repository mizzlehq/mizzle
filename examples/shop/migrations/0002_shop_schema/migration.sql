CREATE VIEW "product_ratings" AS
SELECT "reviews"."product_id" AS "product_id", count(*) AS "reviews", avg("reviews"."rating") AS "rating" FROM "reviews" GROUP BY "reviews"."product_id";
-- mizzle:breakpoint
CREATE MATERIALIZED VIEW "store_sales" AS
SELECT "orders"."store_id" AS "store_id", count(*) AS "orders", sum("orders"."total") AS "revenue" FROM "orders" WHERE "orders"."status" = 'paid' GROUP BY "orders"."store_id";
