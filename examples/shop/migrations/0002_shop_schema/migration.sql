CREATE SCHEMA IF NOT EXISTS "shop_audit";
-- mizzle:breakpoint
CREATE TYPE "user_role" AS ENUM ('customer', 'seller', 'admin');
-- mizzle:breakpoint
CREATE TYPE "order_status" AS ENUM ('pending', 'paid', 'shipped', 'cancelled');
-- mizzle:breakpoint
CREATE TYPE "shop_audit"."audit_action" AS ENUM ('insert', 'update', 'delete');
-- mizzle:breakpoint
CREATE TABLE "users" (
    "id" uuid NOT NULL DEFAULT gen_random_uuid(),
    "email" character varying(255) NOT NULL,
    "name" text NOT NULL,
    "role" user_role NOT NULL DEFAULT 'customer',
    "tags" text[] NOT NULL DEFAULT '{}',
    "prefs" jsonb NOT NULL DEFAULT '{}',
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "users_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "users_email_format" CHECK (email LIKE '%_@_%')
);
-- mizzle:breakpoint
CREATE TABLE "stores" (
    "id" integer GENERATED ALWAYS AS IDENTITY (START WITH 100) NOT NULL,
    "owner_id" uuid NOT NULL,
    "slug" character varying(40) NOT NULL,
    "name" text NOT NULL,
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "stores_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "stores_slug_key" UNIQUE ("slug"),
    CONSTRAINT "stores_slug_format" CHECK (slug ~ '^[a-z0-9-]+$')
);
-- mizzle:breakpoint
CREATE TABLE "products" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    "store_id" integer NOT NULL,
    "sku" text NOT NULL,
    "name" text NOT NULL,
    "description" text,
    "price" numeric(10,2) NOT NULL,
    "tags" text[] NOT NULL DEFAULT '{}',
    "attrs" jsonb NOT NULL DEFAULT '{}',
    "active" boolean NOT NULL DEFAULT true,
    "search" tsvector GENERATED ALWAYS AS (setweight(to_tsvector('english', name), 'A') || setweight(to_tsvector('english', coalesce(description, '')), 'B')) STORED,
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "products_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "products_store_id_sku_key" UNIQUE ("store_id", "sku"),
    CONSTRAINT "products_price_positive" CHECK (price >= 0)
);
-- mizzle:breakpoint
CREATE TABLE "inventory" (
    "product_id" bigint NOT NULL,
    "warehouse" text NOT NULL,
    "quantity" integer NOT NULL DEFAULT 0,
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "inventory_pkey" PRIMARY KEY ("product_id", "warehouse"),
    CONSTRAINT "inventory_quantity_not_negative" CHECK (quantity >= 0)
);
-- mizzle:breakpoint
CREATE TABLE "orders" (
    "id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    "user_id" uuid NOT NULL,
    "store_id" integer NOT NULL,
    "status" order_status NOT NULL DEFAULT 'pending',
    "total" numeric(12,2) NOT NULL DEFAULT 0,
    "note" text,
    "placed_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "orders_pkey" PRIMARY KEY ("id")
);
-- mizzle:breakpoint
CREATE TABLE "order_items" (
    "order_id" bigint NOT NULL,
    "line" smallint NOT NULL,
    "product_id" bigint NOT NULL,
    "quantity" integer NOT NULL,
    "unit_price" numeric(10,2) NOT NULL,
    "line_total" numeric(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT "order_items_pkey" PRIMARY KEY ("order_id", "line"),
    CONSTRAINT "order_items_quantity_positive" CHECK (quantity > 0)
);
-- mizzle:breakpoint
CREATE TABLE "reviews" (
    "id" serial NOT NULL,
    "product_id" bigint NOT NULL,
    "user_id" uuid NOT NULL,
    "rating" smallint NOT NULL,
    "body" text NOT NULL DEFAULT '',
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "reviews_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "reviews_product_id_user_id_key" UNIQUE ("product_id", "user_id"),
    CONSTRAINT "reviews_rating_range" CHECK (rating BETWEEN 1 AND 5)
);
-- mizzle:breakpoint
CREATE TABLE "notifications" (
    "id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    "user_id" uuid NOT NULL,
    "kind" text NOT NULL,
    "payload" jsonb NOT NULL DEFAULT '{}',
    "read_at" timestamp with time zone,
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "notifications_pkey" PRIMARY KEY ("id")
);
-- mizzle:breakpoint
CREATE TABLE "shop_audit"."audit_log" (
    "id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    "table_name" text NOT NULL,
    "action" shop_audit.audit_action NOT NULL,
    "row_id" text NOT NULL,
    "data" jsonb,
    "actor" text NOT NULL DEFAULT CURRENT_USER,
    "at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "audit_log_pkey" PRIMARY KEY ("id")
);
