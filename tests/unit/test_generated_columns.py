dialect = PostgresDialect()
STAMP = dt.datetime(2026, 1, 2, 3, 4, 5)


@final
class Docs(Table, name="docs"):
    id = integer().primary_key().generated_always_as_identity()
    seq = bigint().generated_by_default_as_identity(start=100, increment=5)
    down = smallint().generated_by_default_as_identity(increment=-1)
    body = text().not_null()
    search = array(text()).generated_always_as(sql("string_to_array(body, ' ')"))
    shout = text().generated_always_as(sql("upper(body)"), stored=False)
    embedding = vector(3)
    touched = timestamp().on_update(lambda: STAMP)
    changed = timestamp(tz=True).on_update_now()

    @classmethod
    @override
    def config(cls) -> list[Constraint]:
        return [
            index("docs_search_idx").using("gin").on(cls.search),
            index("docs_embedding_idx")
            .using("hnsw", "vector_cosine_ops")
            .on(cls.embedding)
            .with_(m=16, ef_construction=64),
            index("docs_lower_idx").using("btree", "text_pattern_ops").on(sql("lower(body)")),
        ]


def snap() -> Snapshot:
    return build_snapshot([Docs], dialect)


def test_create_table_sql() -> None:
    statements = [s.sql for s in dialect.render(diff(empty_snapshot("postgresql"), snap()))]
    assert statements[0] == "CREATE EXTENSION IF NOT EXISTS vector"
    create = statements[1]
    for part in [
        '"id" integer GENERATED ALWAYS AS IDENTITY NOT NULL',
        '"seq" bigint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5 START WITH 100) NOT NULL',
        '"down" smallint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY -1) NOT NULL',
        "\"search\" text[] GENERATED ALWAYS AS (string_to_array(body, ' ')) STORED",
        '"shout" text GENERATED ALWAYS AS (upper(body)) VIRTUAL',
        '"embedding" vector(3)',
    ]:
        assert part in create, part
    assert statements[2:] == [
        'CREATE INDEX "docs_search_idx" ON "docs" USING gin ("search")',
        'CREATE INDEX "docs_embedding_idx" ON "docs" USING hnsw ("embedding" vector_cosine_ops) '
        "WITH (m = '16', ef_construction = '64')",
        'CREATE INDEX "docs_lower_idx" ON "docs" (lower(body) text_pattern_ops)',
    ]


def _alter(change: str) -> list[str]:
    """SQL that changes Docs' snapshot as ``change`` (applied to a copy) describes."""
    old = snap()
    new = copy.deepcopy(old)
    columns = new["tables"]["public.docs"]["columns"]
    match change:
        case "drop identity":
            del columns["seq"]["identity"]
        case "add identity":
            del old["tables"]["public.docs"]["columns"]["seq"]["identity"]
        case "change identity":
            columns["seq"]["identity"] = {"always": True, "start": 7, "increment": 5}
        case "change expression":
            columns["shout"]["generated"] = {"expression": "lower(body)", "stored": False}
        case "drop expression":
            del columns["search"]["generated"]
        case _:
            del columns["shout"]["generated"]
    return [s.sql for s in dialect.render(diff(old, new))]


def test_alter_identity_and_generated() -> None:
    assert _alter("drop identity") == ['ALTER TABLE "docs" ALTER COLUMN "seq" DROP IDENTITY']
    assert _alter("add identity") == [
        'ALTER TABLE "docs" ALTER COLUMN "seq" ADD GENERATED BY DEFAULT AS IDENTITY '
        "(INCREMENT BY 5 START WITH 100);\n"
        """SELECT setval(pg_get_serial_sequence('"docs"', 'seq'), """
        'greatest(coalesce(max("seq") + 1, 100), 100), false) FROM "docs"'
    ]
    assert _alter("change identity") == [
        'ALTER TABLE "docs" ALTER COLUMN "seq" SET GENERATED ALWAYS SET START WITH 7'
    ]
    # SET EXPRESSION on PostgreSQL 17+; older servers drop and add the column again.
    [change] = _alter("change expression")
    assert 'ALTER COLUMN "shout" SET EXPRESSION AS (lower(body))' in change
    assert "server_version_num')::int >= 170000" in change
    assert """ADD COLUMN "shout" text GENERATED ALWAYS AS (lower(body)) VIRTUAL""" in change
    assert _alter("drop expression") == ['ALTER TABLE "docs" ALTER COLUMN "search" DROP EXPRESSION']
    # A VIRTUAL column has no stored values to keep: dropped and added as a plain column.
    assert _alter("drop virtual") == [
        'ALTER TABLE "docs" DROP COLUMN "shout"',
        'ALTER TABLE "docs" ADD COLUMN "shout" text',
    ]


def test_dropping_identity_comes_before_drop_not_null() -> None:
    old = snap()
    new = copy.deepcopy(old)
    seq = new["tables"]["public.docs"]["columns"]["seq"]
    del seq["identity"]
    seq["not_null"] = False
    assert [s.describe() for s in diff(old, new)] == [
        "drop identity on docs.seq",
        "drop not null on docs.seq",
    ]


def test_generated_expression_ignored_when_not_comparing_expressions() -> None:
    old = snap()
    new = copy.deepcopy(old)
    new["tables"]["public.docs"]["columns"]["shout"]["generated"] = {
        "expression": "x",
        "stored": False,
    }
    assert diff(old, new, compare_expressions=False) == []
    assert diff(old, new) != []


def test_schema_mistakes() -> None:
    def build(column: object) -> None:
        table = type("Bad", (Table,), {"c": column, "__module__": __name__})
        build_snapshot([table], dialect)

    with pytest.raises(SchemaError, match="cannot have a default"):
        build(integer().generated_always_as_identity().default(1))
    with pytest.raises(SchemaError, match="cannot have a default"):
        build(text().generated_always_as(sql("'x'")).default("y"))
    with pytest.raises(SchemaError, match="needs integer"):
        build(text().generated_always_as_identity())
    with pytest.raises(SchemaError, match="on_update"):
        build(text().generated_always_as(sql("'x'")).on_update(lambda: "y"))
    with pytest.raises(SchemaError, match="invalid index method"):
        index("i").using("gin; drop table x")


