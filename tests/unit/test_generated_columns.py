def test_insert_skips_identity_and_rejects_generated(qb: QueryBuilder) -> None:
    assert qb.insert(Docs).values(body="x").to_sql()[0] == (
        'INSERT INTO "docs" ("body") VALUES ($1)'
    )
    for column, value in [("id", 1), ("search", "'x'"), ("shout", "X")]:
        with pytest.raises(QueryError, match=f"Docs.{column} is"):
            qb.insert(Docs).values({"body": "x", column: value})
    # BY DEFAULT identity columns take explicit values
    assert qb.insert(Docs).values(body="x", seq=5).to_sql()[1] == (5, "x")
    with pytest.raises(QueryError, match="generated column"):
        qb.update(Docs).set(search="x")
    with pytest.raises(QueryError, match="GENERATED ALWAYS AS IDENTITY"):
        qb.insert(Docs).values(body="x").on_conflict_do_update(target=Docs.seq, set_={"id": 2})


def test_update_applies_on_update_hooks(qb: QueryBuilder) -> None:
    q = qb.update(Docs).set(body="x").where(eq(Docs.seq, 1))
    assert q.to_sql() == (
        'UPDATE "docs" SET "body" = $1, "touched" = $2, "changed" = now() WHERE "docs"."seq" = $3',
        ("x", STAMP, 1),
    )
    # set explicitly: the hook is not used
    later = dt.datetime(2030, 1, 1)
    q = qb.update(Docs).set(touched=later, changed=None).where(eq(Docs.seq, 1))
    assert q.to_sql()[1] == (later, None, 1)


def test_upsert_applies_on_update_hooks(qb: QueryBuilder) -> None:
    q = (
        qb.insert(Docs)
        .values(seq=1, body="x")
        .on_conflict_do_update(target=Docs.seq, set_={"body": excluded(Docs.body)})
    )
    assert q.to_sql()[0].endswith(
        'ON CONFLICT ("seq") DO UPDATE SET "body" = excluded."body", "touched" = $3, '
        '"changed" = now()'
    )


def test_vector_values_and_distances(qb: QueryBuilder) -> None:
    q = qb.insert(Docs).values(body="x", embedding=[1.0, 2.5, -3])
    assert q.to_sql()[1] == ("x", "[1,2.5,-3]")
    with pytest.raises(QueryError, match="must be numbers"):
        qb.insert(Docs).values(body="x", embedding=["a", "b", "c"]).to_sql()
    assert Docs.embedding.decode("[1,2.5,-3]") == [1.0, 2.5, -3.0]
    q = (
        qb.select({"d": l2_distance(Docs.embedding, [1, 2, 3])})
        .from_(Docs)
        .order_by(cosine_distance(Docs.embedding, (0.5, 0, 0)))
        .limit(5)
    )
    sql_text, params = q.to_sql()
    assert '"docs"."embedding" <-> $1' in sql_text
    assert 'ORDER BY ("docs"."embedding" <=> $2)' in sql_text.replace("ASC", "").rstrip()
    assert params[:2] == ("[1,2,3]", "[0.5,0,0]")


