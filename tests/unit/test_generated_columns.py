def load(source: str, tmp_path: Path) -> list[type[Table]]:
    path = tmp_path / "pulled_generated.py"
    path.write_text(source)
    spec = importlib.util.spec_from_file_location("pulled_generated", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return [
        value
        for value in vars(module).values()
        if isinstance(value, type) and issubclass(value, Table) and value is not Table
    ]


def test_pull_writes_the_new_forms_and_round_trips(tmp_path: Path) -> None:
    source = render_schema_module(snap())
    for line in [
        "id = integer().primary_key().generated_always_as_identity()",
        "seq = bigint().generated_by_default_as_identity(increment=5, start=100)",
        "down = smallint().generated_by_default_as_identity(increment=-1)",
        "search = array(text()).generated_always_as(sql(\"string_to_array(body, ' ')\"))",
        "shout = text().generated_always_as(sql('upper(body)'), stored=False)",
        "embedding = vector(3)",
        "index('docs_search_idx').using('gin').on(cls.search)",
        "index('docs_embedding_idx').using('hnsw', 'vector_cosine_ops').on(cls.embedding)"
        ".with_(m='16', ef_construction='64')",
        "index('docs_lower_idx').on(sql('lower(body) text_pattern_ops'))",
    ]:
        assert line in source, line
    rebuilt = build_snapshot(load(source, tmp_path), dialect)
    assert diff(snap(), rebuilt) == []
    assert diff(rebuilt, snap()) == []


def test_typegen_leaves_out_read_only_columns() -> None:
    source = render_types_module([Docs])
    insert = source.split("class DocsInsert(TypedDict):")[1].split("class")[0]
    assert "    id:" not in insert and "search:" not in insert and "shout:" not in insert
    assert "    seq: NotRequired[int]" in insert
    assert "    embedding: NotRequired[list[float] | None]" in insert


